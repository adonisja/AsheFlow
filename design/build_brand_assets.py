"""Generate the logo/favicon set from design/palette.json (plan 0.5).

    python design/build_brand_assets.py            # write
    python design/build_brand_assets.py --check    # verify in sync (CI)

## Why generated

The repo carried TWO conflicting identities (plan §2.7):

  frontend/src/assets/*.svg      the real mark, on the OLD indigo/amber
  frontend/public/favicon.svg    an unrelated purple lightning bolt — a
                                 leftover template, and the one actually
                                 wired into the browser tab
  frontend/public/icons.svg      purple/cyan, referenced by nothing

Hand-maintained SVGs drift from the palette exactly the way the two theme files
did. Generating them means "change the palette, re-run, done" instead of
editing six files and missing one.

## Interim, not final

The real mark is being commissioned from a human designer. This keeps the
CURRENT mark's geometry (three dots feeding a rounded square, one line out —
an intake/sort/dispatch flow) and only re-colours it onto the settled palette,
so nothing in the UI contradicts the tokens while that work happens.

When the designer delivers, replace the geometry in this file; the colour
plumbing stays.
"""
from __future__ import annotations

import colorsys
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
REPO = ROOT.parent
SPEC = ROOT / "palette.json"
ASSETS = REPO / "frontend" / "src" / "assets"
PUBLIC = REPO / "frontend" / "public"
ANDROID_RES = REPO / "mobile" / "android" / "app" / "src" / "main" / "res"

BANNER = "AUTO-GENERATED by design/build_brand_assets.py from design/palette.json"


def hsl(spec: dict, theme: str, token: str) -> str:
    h, s, l = spec[theme][token]["hsl"]
    return f"hsl({h} {s}% {l}%)"


def _mark_paths(stroke: str, block: str, dot: str) -> str:
    """The AsheFlow mark: three inputs converge into a block, one output.

    Geometry preserved from the existing mark — only the colours change.
    """
    return f"""  <line x1="4" y1="13" x2="17" y2="22" stroke="{stroke}" stroke-width="2.6" stroke-linecap="round"/>
  <line x1="4" y1="24" x2="17" y2="24" stroke="{stroke}" stroke-width="2.6" stroke-linecap="round"/>
  <line x1="4" y1="35" x2="17" y2="26" stroke="{stroke}" stroke-width="2.6" stroke-linecap="round"/>
  <circle cx="5" cy="13" r="2.2" fill="{stroke}"/>
  <circle cx="5" cy="24" r="2.2" fill="{stroke}"/>
  <circle cx="5" cy="35" r="2.2" fill="{stroke}"/>
  <rect x="16" y="16" width="16" height="16" rx="3.5" fill="{block}"/>
  <rect x="20.5" y="20.5" width="7" height="7" rx="1.2" fill="{dot}" opacity="0.95"/>
  <line x1="32" y1="24" x2="41" y2="24" stroke="{block}" stroke-width="2.6" stroke-linecap="round"/>"""


def build(spec: dict) -> dict[pathlib.Path, str]:
    # Light surfaces: navy block, amber inputs. Dark surfaces: the lifted
    # variants, because navy on near-black is unreadable.
    navy_l, gold_l = hsl(spec, "light", "primary"), hsl(spec, "light", "gold")
    navy_d, gold_d = hsl(spec, "dark", "primary"), hsl(spec, "dark", "gold")
    fg_l, fg_d = hsl(spec, "light", "foreground"), hsl(spec, "dark", "foreground")

    out: dict[pathlib.Path, str] = {}

    def svg(view: str, body: str) -> str:
        return (f'<!-- {BANNER} -->\n'
                f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" fill="none" '
                f'role="img" aria-label="AsheFlow">\n{body}\n</svg>\n')

    out[ASSETS / "logo-mark.svg"] = svg("0 0 48 48", _mark_paths(gold_l, navy_l, "white"))
    out[ASSETS / "logo-mark-light.svg"] = svg("0 0 48 48", _mark_paths(gold_d, navy_d, fg_d))

    # Favicon: a filled tile so the mark reads at 16px against any tab colour.
    out[ASSETS / "favicon.svg"] = svg(
        "0 0 48 48",
        f'  <rect width="48" height="48" rx="10" fill="{navy_l}"/>\n'
        + _mark_paths(gold_d, "white", navy_l).replace(
            'fill="white" opacity="0.95"', f'fill="{navy_l}" opacity="0.95"')
    )
    # The browser tab currently points at public/ — keep both identical rather
    # than leaving a second, divergent file (that is how the bolt survived).
    out[PUBLIC / "favicon.svg"] = out[ASSETS / "favicon.svg"]

    wordmark = ('  <text x="0" y="34" font-family="Sora, Inter, system-ui, sans-serif" '
                'font-size="30" font-weight="700" fill="{fill}">AsheFlow</text>')
    out[ASSETS / "logo-wordmark.svg"] = svg("0 0 190 48", wordmark.format(fill=fg_l))

    # The lockup's canvas ends where its ink ends. It was 245 wide with the
    # drawing ending near 183, so the logo carried ~60 units of empty space on
    # its right: centred as a box, its INK sat 25px left of centre at 1920px,
    # and the sign-in card beneath read as shifted right (owner, 2026-10-20).
    #
    # textLength pins the wordmark's width. An SVG loaded through <img> cannot
    # use the page's web fonts, so the text renders in whatever Sora/Inter/
    # system-ui fallback each device has -- a different width on every
    # machine, and no fixed viewBox can fit all of them. Pinned, it is 124
    # units everywhere: x 60 -> 184. The mark's ink starts at 2.8 (circle cx 5,
    # r 2.2), so a 186.8 canvas leaves equal margins and centres the ink.
    lock = ('{mark}\n  <text x="60" y="33" font-family="Sora, Inter, system-ui, sans-serif" '
            'font-size="27" font-weight="700" textLength="124" lengthAdjust="spacingAndGlyphs" '
            'fill="{fill}">AsheFlow</text>')
    out[ASSETS / "logo-full.svg"] = svg(
        "0 0 186.8 48", lock.format(mark=_mark_paths(gold_l, navy_l, "white"), fill=fg_l))
    out[ASSETS / "logo-full-light.svg"] = svg(
        "0 0 186.8 48", lock.format(mark=_mark_paths(gold_d, navy_d, fg_d), fill=fg_d))
    return out


# ── Android (ADR-570) ────────────────────────────────────────────────────────
# The same mark as the web, as Android resources. Vector drawables take only
# path data, so each primitive of _mark_paths is restated as a path here: the
# geometry below is THE SAME NUMBERS, and test_adr570 checks they stay equal.
_LINES_IN = [((4, 13), (17, 22)), ((4, 24), (17, 24)), ((4, 35), (17, 26))]
_DOTS = [(5, 13), (5, 24), (5, 35)]
_BLOCK = (16, 16, 16, 16, 3.5)      # x, y, w, h, corner radius
_CORE = (20.5, 20.5, 7, 7, 1.2)
_LINE_OUT = ((32, 24), (41, 24))

# Mark ink in the 48-unit box: x 2.8 (first dot) .. 42.3 (output cap), y 10.8 .. 37.2.
_INK_CX, _INK_CY = (2.8 + 42.3) / 2, 24.0


def hex_colour(spec: dict, theme: str, token: str) -> str:
    """palette.json HSL -> #RRGGBB (Android colour resources take hex)."""
    h, s, l = spec[theme][token]["hsl"]
    r, g, b = colorsys.hls_to_rgb(h / 360, l / 100, s / 100)
    return "#{:02X}{:02X}{:02X}".format(round(r * 255), round(g * 255), round(b * 255))


def _f(n: float) -> str:
    return f"{n:g}"


def _circle_d(cx: float, cy: float, r: float) -> str:
    return (f"M{_f(cx - r)},{_f(cy)} a{_f(r)},{_f(r)} 0 1,0 {_f(2 * r)},0 "
            f"a{_f(r)},{_f(r)} 0 1,0 {_f(-2 * r)},0 Z")


def _rrect_d(x: float, y: float, w: float, h: float, r: float) -> str:
    return (f"M{_f(x + r)},{_f(y)} H{_f(x + w - r)} A{_f(r)},{_f(r)} 0 0,1 {_f(x + w)},{_f(y + r)} "
            f"V{_f(y + h - r)} A{_f(r)},{_f(r)} 0 0,1 {_f(x + w - r)},{_f(y + h)} "
            f"H{_f(x + r)} A{_f(r)},{_f(r)} 0 0,1 {_f(x)},{_f(y + h - r)} "
            f"V{_f(y + r)} A{_f(r)},{_f(r)} 0 0,1 {_f(x + r)},{_f(y)} Z")


def _stroke(a, b, colour: str, width: float) -> str:
    return (f'    <path android:pathData="M{_f(a[0])},{_f(a[1])} L{_f(b[0])},{_f(b[1])}" '
            f'android:strokeColor="{colour}" android:strokeWidth="{_f(width)}" '
            f'android:strokeLineCap="round"/>')


def _fill(d: str, colour: str, even_odd: bool = False) -> str:
    rule = ' android:fillType="evenOdd"' if even_odd else ""
    return f'    <path android:pathData="{d}" android:fillColor="{colour}"{rule}/>'


def _mark_vector(inputs: str, block: str, core: str) -> list[str]:
    """The coloured mark, for the launcher foreground."""
    out = [_stroke(a, b, inputs, 2.6) for a, b in _LINES_IN]
    out += [_fill(_circle_d(x, y, 2.2), inputs) for x, y in _DOTS]
    out += [_fill(_rrect_d(*_BLOCK), block), _fill(_rrect_d(*_CORE), core),
            _stroke(*_LINE_OUT, block, 2.6)]
    return out


def _mark_silhouette(colour: str = "#FFFFFFFF") -> list[str]:
    """One colour, for the notification and themed icons. The core is CUT OUT
    of the block (even-odd), because a white square on a white block vanishes;
    strokes are thicker than the web's 2.6 so they read at 24 dp."""
    out = [_stroke(a, b, colour, 3.4) for a, b in _LINES_IN]
    out += [_fill(_circle_d(x, y, 2.6), colour) for x, y in _DOTS]
    out += [_fill(_rrect_d(*_BLOCK) + " " + _rrect_d(*_CORE), colour, even_odd=True),
            _stroke(*_LINE_OUT, colour, 3.4)]
    return out


def _vector(size_dp: int, viewport: float, body: list[str], group: str | None = None) -> str:
    inner = "\n".join(body)
    if group:
        inner = f"  <group {group}>\n{inner}\n  </group>"
    return (f"<!-- {BANNER} -->\n"
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{_f(viewport)}" android:viewportHeight="{_f(viewport)}">\n'
            f"{inner}\n</vector>\n")


def _in_safe_zone(scale: float = 1.5) -> str:
    """Centre the 48-unit mark in a 108 dp adaptive layer. Ink 39.5 units wide x
    1.5 = 59 dp, inside the 66 dp zone no launcher mask clips."""
    tx, ty = 54 - _INK_CX * scale, 54 - _INK_CY * scale
    return (f'android:translateX="{_f(round(tx, 3))}" android:translateY="{_f(round(ty, 3))}" '
            f'android:scaleX="{_f(scale)}" android:scaleY="{_f(scale)}"')


def build_android(spec: dict) -> dict[pathlib.Path, str]:
    navy = hex_colour(spec, "light", "primary")
    gold_on_navy = hex_colour(spec, "dark", "gold")   # the favicon's colouring
    out: dict[pathlib.Path, str] = {}
    out[ANDROID_RES / "drawable" / "ic_notification.xml"] = _vector(24, 48, _mark_silhouette())
    out[ANDROID_RES / "drawable" / "ic_launcher_foreground.xml"] = _vector(
        108, 108, _mark_vector(gold_on_navy, "#FFFFFFFF", navy), group=_in_safe_zone())
    out[ANDROID_RES / "drawable" / "ic_launcher_monochrome.xml"] = _vector(
        108, 108, _mark_silhouette("#FF000000"), group=_in_safe_zone())
    adaptive = (f"<!-- {BANNER} -->\n"
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@color/ic_launcher_background"/>\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
                "</adaptive-icon>\n")
    out[ANDROID_RES / "mipmap-anydpi-v26" / "ic_launcher.xml"] = adaptive
    out[ANDROID_RES / "mipmap-anydpi-v26" / "ic_launcher_round.xml"] = adaptive
    out[ANDROID_RES / "values" / "brand_colors.xml"] = (
        f"<!-- {BANNER} -->\n<resources>\n"
        f'    <color name="ic_launcher_background">{navy}</color>\n'
        f"    <!-- Tints the push icon and app name in the shade (firebase.json). -->\n"
        f'    <color name="notification_accent">{navy}</color>\n'
        "</resources>\n")
    return out


def main(check_only: bool = False) -> int:
    spec = json.loads(SPEC.read_text())
    outputs = {**build(spec), **build_android(spec)}

    if check_only:
        stale = [p.relative_to(REPO) for p, c in outputs.items()
                 if not p.exists() or p.read_text() != c]
        if stale:
            print("\nBRAND ASSETS ARE STALE:\n")
            for p in stale:
                print(f"  {p}")
            print("\nRun `python design/build_brand_assets.py` and commit the result.")
            return 1
        print(f"OK — {len(outputs)} brand assets match the palette")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"  wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(check_only="--check" in sys.argv))
