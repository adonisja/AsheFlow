"""Every notification type's severity, channels, label and tone (ADR-487 D1).

ONE TABLE, BECAUSE THE ALTERNATIVE WAS FOUR
===========================================

Before this, routing a notification was decided in four independent places and
none of them was complete:

    backend literals        61 types   what actually exists
    TYPE_META (mobile)      48 types   label + icon
    typeColor (mobile)      18 exact + 5 substring rules
    styleForType (web)       4 exact + 4 pattern rules

31 backend types had no mobile label — including every urgent one. The web's
pattern rules gave `incident_critical_injury` a warning treatment only because
somebody happened to put the word "critical" in the name; rename it and an injury
alert silently becomes a plain grey card. Measured across the corpus, 30 of 61
type names matched no naming convention at all.

TWO INDEPENDENT AXES
====================

The channel set says WHERE a notification goes. Severity governs only QUIET
HOURS. They are not derived from each other, and the registry proves why:

    dispatch_finalized              INFO    pushes      (the crew's need-to-know)
    manifest_enrichment             INFO    no push     (a background job)
    dispatch_finalization_reminder  ACTION  no push     (fires on a timer)

So INFO does not mean "quiet" — it means "nothing is waiting on you", and plenty
of things nobody must answer still have to arrive.

WHY A TONE AND NOT A COLOUR
===========================

Mobile's palette is generated by `design/build_tokens.py` and contrast-checked in
CI; the web's comes from Tailwind CSS variables. They are independently generated
and independently verified, so a hex value from this file would bypass both. The
server says what a message MEANS and each client maps that to its own token.

AN UNDECLARED TYPE RAISES. IT DOES NOT DEFAULT.
===============================================

`resolve_spec` refuses rather than falling back to INFO, because a default of INFO
is exactly today's behaviour — a lenient lookup would make this file decorative
and pass silently in the one case it exists to catch. See ADR-487 D1.
"""
from __future__ import annotations

from dataclasses import dataclass
from enum import Flag, StrEnum, auto


class Severity(StrEnum):
    """What it costs to miss this. Governs quiet hours, nothing else."""

    URGENT = "urgent"   # somebody is hurt, or the operation is stopping
    ACTION = "action"   # waiting on THIS person's response
    NOTICE = "notice"   # tenant-authored or platform-seeded, fires because a time arrived
    INFO = "info"       # a system or third-party event; nobody is blocked


class Channel(Flag):
    """Where it goes. INBOX is unconditional and therefore absent.

    Every notification is a row whatever else happens to it, so a channel set of
    TICKER means "ticker and the archive", never "ticker instead of a record".
    """

    NONE = 0
    BANNER = auto()     # web banner / mobile Today card (ADR-275)
    TICKER = auto()     # the scrolling strip (D4b)
    PUSH = auto()       # APNs / FCM via SNS (D5)
    DISCORD = auto()    # secondary surface, never the channel of record (ADR-324)
    GATE = auto()       # root-navigator swap; cannot be worked around (D8)
    PROMPT = auto()     # escapable modal, once per launch (D8)


class Tone(StrEnum):
    """The semantic colour role. NOT a hex value and NOT a token name."""

    NEUTRAL = "neutral"
    GOOD = "good"
    WARN = "warn"
    BAD = "bad"
    ACTIVE = "active"


@dataclass(frozen=True)
class NotificationAction:
    """A control the notification CARRIES, rather than a page it names.

    ADR-487 D10's Finding A: *naming the action in prose is not enough — the
    message carries the control.* An ACTION notification whose remedy is a
    sentence makes the reader go and find the page; one that carries the
    affordance IS the remedy.

    Named `NotificationAction` rather than `Action` deliberately: `ACTION` is
    already the Severity constant in this module, and `Action`/`ACTION` differing
    only by case is the kind of pair that reads correctly and imports wrongly.

    `route` is a WEB PATH, and it is the same string for both surfaces by
    contract: a gate's only exit is this link, so if web and mobile disagreed
    about where it goes, one of them would lock the user against a dead end.

    NOT YET CONSUMED BY EITHER CLIENT. Web resolves these paths directly
    (every one is a real route in App.tsx -- checked, because a link to a 404
    is the ADR-381 failure). Mobile navigates by SCREEN NAME, not by path, and
    has no linking config, so it needs a path->screen map before these
    resolve there. Until that exists the field is inert on mobile rather than
    wrong, and the prompt/gate UI that reads it is the remaining ADR-494 work.
    Stated here rather than implied, because a docstring claiming "mobile maps
    the path to its own navigator" is how an unbuilt surface reads as shipped.

    `style` is a semantic role, never a colour — the same reasoning as `tone`
    (ADR-487 D4). The two surfaces own different palettes, so a hex here would
    land in one of the two themes unreadable.
    """

    label: str                    # "Accept", "Assign truck", "Go to Field Ops"
    route: str                    # the client path; identical on web and mobile
    style: str = "default"        # "default" | "primary" | "danger"


@dataclass(frozen=True)
class Spec:
    severity: Severity
    channels: Channel
    label: str          # the short noun phrase a human reads
    tone: Tone
    icon: str           # one emoji; mobile renders it, web maps it to a glyph
    #: Controls the client renders ON the notification (ADR-487 D10 Finding A).
    #: A tuple so Spec stays hashable and frozen; empty for the ~75 types whose
    #: remedy is "read it", because a control that goes nowhere useful is worse
    #: than no control.
    actions: tuple[NotificationAction, ...] = ()


class UndeclaredNotificationType(RuntimeError):
    """Raised by resolve_spec for a type with no entry. Never caught to default."""


